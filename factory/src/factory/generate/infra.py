"""Bicep IaC for a generated app, derived from design.json (ADR-010).

Hosting choices: API on Azure Container Apps (scale to zero, revisions, managed identity);
React UI on Static Web Apps; Cosmos DB for NoSQL (serverless, local auth disabled, one
container per Dataverse table with the design partition key and PII paths excluded from
the index); one Function App for the migrated flows (Durable where a flow waits on a human).
Secrets: none. Every service authenticates with the user-assigned managed identity.
"""

